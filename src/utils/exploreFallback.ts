export function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim()
}

export function resolveStayCoordinates(stay: FeaturedStay): [number, number] {
  const lat = stay.latitude ?? stay.address?.latitude
  const lng = stay.longitude ?? stay.address?.longitude
  if (
    typeof lat === 'number' &&
    typeof lng === 'number' &&
    !Number.isNaN(lat) &&
    !Number.isNaN(lng)
  ) {
    return [lat, lng]
  }

  const cityKey = normalizeText(stay.address?.city ?? '')
  const stateKey = normalizeText(stay.address?.state ?? '')

  let base: [number, number] | undefined = MEXICO_CITY_COORDS[cityKey]

  if (!base) {
    for (const [key, coords] of Object.entries(MEXICO_CITY_COORDS)) {
      if (cityKey.includes(key) || stateKey.includes(key)) {
        base = coords
        break
      }
    }
  }

  const center: [number, number] = base ?? [19.4326, -99.1332]
  // Desplazamiento determinístico suave según el ID para separar pines en la misma ciudad
  const angle = ((stay.id * 137.5) % 360) * (Math.PI / 180)
  const radius = 0.008 + ((stay.id % 5) * 0.004)
  return [
    Number((center[0] + Math.sin(angle) * radius).toFixed(5)),
    Number((center[1] + Math.cos(angle) * radius).toFixed(5)),
  ]
}

